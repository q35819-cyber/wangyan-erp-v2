-- 修正历史主题标签规则：Ozon 主题标签必须按平台格式生成，不能使用旧版“纯中文短语/禁止#”规则。
-- 只更新明确属于旧规则的记录，避免覆盖系统管理员已经手工修正过的新规则。
UPDATE ai_product_content_rules
SET body = '主题标签必须符合当前类目说明，只用于描述商品的趋势、风格或主题，不得包含品牌、商品参数或商品名称。每个标签必须以#开头；#后的主体使用字母和数字，两个及以上单词必须仅用下划线连接。单个主题标签最大30个字符。最多30个主题标签，多个标签之间用一个空格分隔。禁止使用逗号、分号、项目符号或其它分隔方式。用于Ozon正式字段时输出俄语主题标签；如系统同时生成中文对照，中文只用于ERP翻译查看，不写入Ozon正式字段。',
    updated_at = now()
WHERE rule_key = 'tags'
  AND (
    body = '使用相关、可检索的中文短语。'
    OR body ILIKE '%纯中文短语%'
    OR body ILIKE '%禁止包含“#”%'
    OR body ILIKE '%禁止包含"#"%'
  );
