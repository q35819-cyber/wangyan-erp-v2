-- 进一步细化 Ozon 主题标签生成策略。051 已执行，不回改历史迁移；本迁移只升级仍处于 051/旧版规则的标签规则。
UPDATE ai_product_content_rules
SET body = '生成主题标签前，必须读取当前商品的类目说明、标题、类目属性、变体和其它已知事实，并以当前类目说明为最高优先级。主题标签只用于表达与商品真实信息一致的趋势、风格、主题、场景或明确适用人群；不得填写品牌、商品名称、SKU、型号、价格、促销词，也不得机械复制颜色、尺寸、容量、功率等结构化参数。正式Ozon字段优先输出俄语主题标签。每个标签必须以#开头；标签主体只允许字母、数字和下划线；两个及以上单词必须用下划线连接；单个主题标签最大30个字符；最多30个主题标签；多个标签之间只用一个空格分隔，不使用逗号、分号、换行、项目符号或其它分隔符。质量优先，不要求凑满30个；通常生成约8-15个高相关标签，商品事实不足时可以更少，禁止为了数量编造场景、功能、人群或趋势。优先选择精准且有实际相关性的标签，避免宽泛、低相关的大词。节日、促销季或热点标签只有在商品确实适配，并且当前事实或上下文明示处于对应活动周期时才允许生成；不能凭空追热点。人群标签只有在类目或商品属性明确给出适用人群时才允许生成，禁止根据图片或主观印象推断。对于强搜索属性商品，也不得把型号或性能参数直接当主题标签；缺乏合适主题时宁可少生成。若同时生成中文对照，中文只用于ERP翻译查看和本地草稿，不写入Ozon正式字段。',
    updated_at = now()
WHERE rule_key = 'tags'
  AND (
    body = '主题标签必须符合当前类目说明，只用于描述商品的趋势、风格或主题，不得包含品牌、商品参数或商品名称。每个标签必须以#开头；#后的主体使用字母和数字，两个及以上单词必须仅用下划线连接。单个主题标签最大30个字符。最多30个主题标签，多个标签之间用一个空格分隔。禁止使用逗号、分号、项目符号或其它分隔方式。用于Ozon正式字段时输出俄语主题标签；如系统同时生成中文对照，中文只用于ERP翻译查看，不写入Ozon正式字段。'
    OR body = '使用相关、可检索的中文短语。'
    OR body ILIKE '%纯中文短语%'
    OR body ILIKE '%禁止包含“#”%'
    OR body ILIKE '%禁止包含"#"%'
  );
