-- 055：完善商品内容全局事实规则，移除“真实品牌也禁止出现”等遗留冲突。
-- 只升级 031 初始默认值和 2026-09-14 已知旧规则，保留其它管理员自定义全局规则。
UPDATE ai_product_content_rules
SET body = $new_rule$所有商品内容必须以当前已确认的商品事实为唯一依据，并优先遵守当前Ozon类目说明、字段说明和结构化属性要求；类目或字段有更具体要求时，以更具体的要求为准。允许使用商品事实中真实存在的品牌、型号、材质、规格、适用对象、配件和用途，但不得编造、扩大、弱化或替换事实；信息缺失时直接省略，不得猜测补全。所有数字必须来自商品事实并保持数值含义一致，不得自行增加、修改或换算成新的数值；单位写法可以按目标语言正常表达，但不得改变计量含义。禁止编造性能、认证、实验结果、排名、百分比、对比优势、价格、折扣、促销、配送承诺、售后承诺或其它无法验证的说法。禁止把供应商沟通、工厂话术、内部物流箱规、采购备注、平台后台说明等与买家无关的信息直接写入商品内容。不得根据图片、主观印象或常识推断未确认的商品事实。标题、简介、主题标签、卖点和其它内容之间不得互相矛盾；同一事实的数字、材质、型号、颜色、容量、配件和适用范围必须一致。正式Ozon业务字段使用自然俄语；如同时生成中文对照，中文只用于ERP审核和浏览器草稿，不写入Ozon正式字段。$new_rule$,
    updated_at = now()
WHERE rule_key = 'global'
  AND (
    body = '所有内容必须忠于商品来源事实，保留数字和单位，不编造品牌、性能、认证、价格、促销或无法验证的承诺。'
    OR body = $legacy_rule$禁止出现品牌、工厂、直销、跨境、营销广告、无意义的词汇（如：女神、轻奢、颜值在线、烂大街）。所有内容必须忠于商品来源事实，保留数字和单位。严禁编造品牌、性能、认证、价格、促销或无法验证的承诺（如：绝对防摔、不易碎）。不输出主观评价，不输出价格暗示。$legacy_rule$
  );
